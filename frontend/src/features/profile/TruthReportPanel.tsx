import { Icon } from "@/components/IconSprite";
import { Stars } from "@/components/chrome";
import { rankLabel } from "@/lib/makeupGrade";
import { tierStars, type SieveResult } from "@/lib/metricSieve";
import type { FilmState } from "./useFilmJob";

/**
 * The AI Truth Report card.
 *
 * Before the first generation this is the static placeholder the page always
 * showed. After it, the layout is a component-for-component port of the
 * `run()` template string: rating card, evidence strip, tier ladder, the metric
 * table, the out-of-bracket flag, strengths/weaknesses, and the film section.
 *
 * Strengths and weaknesses are still derived directly from the sieve's own
 * pass/fail checks — nothing fabricated or pulled from outside data.
 */

export interface GeneratedReport {
  sieve: SieveResult;
  /** Snapshotted when the report was generated, as the original did. */
  playerNumber: string;
  stamp: string;
  film: FilmState;
}

export function TruthReportPanel({ report }: { report: GeneratedReport | null }) {
  // Generating the report replaced the whole card in Phase 15, hero strip
  // included, so the two states are rendered as alternatives rather than
  // stacked.
  return (
    <div className="card" id="report" aria-live="polite">
      {report ? <GeneratedBody report={report} /> : <PlaceholderBody />}
    </div>
  );
}

